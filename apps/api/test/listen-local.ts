import type { INestApplication } from '@nestjs/common';

/**
 * Запуск приложения в сквозном тесте вместо `app.init()`: сервер один раз занимает свободный порт на 127.0.0.1.
 *
 * Иначе supertest на каждый запрос открывает сервер на случайном порту всех адресов и закрывает его после ответа.
 * На macOS такой порт может совпасть с портом, который на 127.0.0.1 слушает другая программа (VS Code, OrbStack,
 * Termius) или поддельный сервер самого теста, — и запрос уходит ей: чужой 404, обрыв соединения или зависание,
 * каждый раз в другом тесте. Одновременные запросы (Promise.all) к тому же закрывали сервер друг у друга.
 */
export async function listenLocal(app: INestApplication): Promise<void> {
  await app.listen(0, '127.0.0.1');
}
