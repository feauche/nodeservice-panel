-- Порог «Агент не в сети» теперь не меньше 30 секунд (три сигнала агента). Сохранённое меньшее значение
-- (раньше разрешалось от 10) поднимаем до минимума: иначе настройки «Автопроверки» перестали бы проходить
-- проверку и весь раздел молча вернулся бы к значениям по умолчанию. Правим текстом, без приведения к
-- jsonb: повреждённая запись не должна останавливать запуск панели. Повторный запуск ничего не меняет.
UPDATE "app_meta"
SET "value" = regexp_replace("value", '("agentOfflineAfterSeconds"\s*:\s*)[12][0-9](\s*[,}])', '\130\2')
WHERE "key" = 'settings.autochecks'
  AND "value" ~ '"agentOfflineAfterSeconds"\s*:\s*[12][0-9]\s*[,}]';
