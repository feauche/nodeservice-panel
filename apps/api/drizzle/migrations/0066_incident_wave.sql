-- 0.106.0: волна — одно общее событие для нод одного провайдера (или страны), упавших почти одновременно.
-- У волны нет одной ноды (node_uuid пустой), поэтому прежние индексы «одно открытое событие на ноду и вид» её не
-- защищают: две открытые волны одной группы не должны появиться даже при одновременной обработке снимков.
CREATE UNIQUE INDEX IF NOT EXISTS "incidents_wave_open_unique" ON "incidents" ((("snapshot"->'fleet'->>'groupKey')))
  WHERE "kind" = 'wave' AND "status" <> 'resolved';
