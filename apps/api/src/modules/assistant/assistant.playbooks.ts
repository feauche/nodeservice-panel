/**
 * Плейбуки разбора (R4.5) для нод Remnawave: что посмотреть в данных, как это читать, что рекомендовать
 * владельцу и чего панель не видит. Живут в коде, а не в базе знаний: один метод для всех разборов, правится
 * вместе с инструментами. Ассистент ничего не запускает: проверки и шаги в разделе «рекомендовать» — советы
 * владельцу с путём по интерфейсу, нажимает он сам.
 */
export interface Playbook {
  id: string;
  title: string;
  when: string;
  /** Виды событий, для которых плейбук подходит. Пусто — по вопросу владельца, без события. */
  kinds: IncidentKind[];
  /** Что посмотреть в данных по порядку: только инструменты чтения. */
  steps: string[];
  /** Как читать увиденное. */
  reading: string[];
  /** Что рекомендовать владельцу: проверка или шаг, путь по интерфейсу, что это покажет. */
  recommend: string[];
  /** Чего панель не видит: об этом Ассистент говорит прямо, а не догадывается. */
  limits: string[];
}

