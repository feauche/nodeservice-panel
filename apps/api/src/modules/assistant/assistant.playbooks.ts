export const playbookById = (id: string): Playbook | undefined => PLAYBOOKS.find((p) => p.id === id);

export const playbookForKind = (kind: IncidentKind): Playbook | undefined =>
  PLAYBOOKS.find((p) => p.kinds.includes(kind));

/** Плейбук текстом для модели. */
export function renderPlaybook(p: Playbook): string {
  const list = (items: string[]) => items.map((x, i) => `${i + 1}. ${x}`).join('\n');
  return [
    `ПЛЕЙБУК «${p.title}» (${p.id}). Когда: ${p.when}`,
    `Что проверить по порядку:\n${list(p.steps)}`,
    `Как читать результат:\n${list(p.reading)}`,
    `Что предлагать (уровни T0–T3 из реестра, T3 только текстом):\n${list(p.actions)}`,
    `Чего панель не видит (скажите об этом прямо):\n${list(p.limits)}`,
  ].join('\n\n');
}
