    return 'ПОДРОБНОСТЬ — «ПОДРОБНО»: объясняй максимально подробно и простыми словами. Любую аббревиатуру и технический термин (даже TCP, DPI, процессор и нагрузка) коротко расшифровывай при первом упоминании. Не пропускай очевидные для тебя шаги.';
