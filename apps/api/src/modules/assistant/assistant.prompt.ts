/** Карта панели: навигация и типовые пути. Вынесена вниз промпта: в начале правила, в конце справка. */
export /** Инструкция под подробность ответов. */
function levelRule(level: AssistantLevel): string {
  if (level === 'novice')
    return 'ПОДРОБНОСТЬ — «ПОДРОБНО»: объясняй максимально подробно и простыми словами. Любую аббревиатуру и технический термин (даже SSH, CPU, conntrack) коротко расшифровывай при первом упоминании. Не пропускай очевидные для тебя шаги.';
  if (level === 'pro')
    return 'ПОДРОБНОСТЬ — «КРАТКО»: пиши кратко и плотно, можно терминами и аббревиатурами без расшифровки. Не разжёвывай базовое и не повторяй очевидное.';
  return 'ПОДРОБНОСТЬ — «ОБЫЧНО»: по делу, но поясняй неочевидные термины и шаги. Баланс между подробностью и краткостью.';
}

