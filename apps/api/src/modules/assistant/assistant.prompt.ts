/** Текущее время и пояс панели: данные инструментов приходят в UTC, владелец живёт в поясе панели. */
function timeLine(now: Date, timeZone: string | null | undefined): string {
  const utc = now.toISOString();
  if (!timeZone)
    return `ТЕКУЩЕЕ ВРЕМЯ (UTC): ${utc}. Пояс панели не передан: время из данных называй с пометкой «UTC».`;
  const zone = safeTimeZone(timeZone);
  const label = zoneLabel(now, zone);
  return `ТЕКУЩЕЕ ВРЕМЯ: ${utc} (UTC). Пояс панели — ${zone} (${label}), там сейчас ${localDateTime(now, zone, now, { year: true })}. Все времена в ответе называй в поясе панели с пометкой «${label}»: данные инструментов приходят в UTC — переводи их.`;
}

const INTEGRATION_NAMES: Record<string, string> = {
  dpi: 'DPI Checker',
  bschecker: 'BS Checker',
  regru: 'REG.RU (DNS)',
  cloudflare: 'Cloudflare (DNS)',
};

/** Строка из пользовательских данных в одну строку и без лишней длины: это данные, а не инструкции. */
const oneLine = (s: string, max: number): string => s.replace(/\s+/g, ' ').trim().slice(0, max);

/** Какие интеграции подключены: от этого зависит, советовать проверку или сначала подключение. */
function integrationsLine(items: PromptIntegration[] | undefined): string {
  if (!items) return '';
  if (items.length === 0) return 'ИНТЕГРАЦИИ СЕЙЧАС: ни одна не подключена.';
  const parts = items.map((i) => {
    const name = INTEGRATION_NAMES[i.provider] ?? oneLine(i.provider, 40);
    if (!i.connected) return `${name} — не подключена`;
    return `${name} — подключена${i.balance ? `, баланс ${oneLine(i.balance, 40)}` : ''}`;
  });
  return `ИНТЕГРАЦИИ СЕЙЧАС: ${parts.join('; ')}.`;
}

/** Названия «Своих сайтов» из меню владельца: чтобы на вопрос «что за ссылка в меню» был ответ. */
function customSitesLine(sites: Array<{ name: string }> | undefined): string {
  if (!sites) return '';
  const names = sites.map((s) => oneLine(s.name, 40)).filter(Boolean);
  return names.length > 0
    ? `СВОИ САЙТЫ В МЕНЮ (названия, которые дал владелец; содержимого сайтов ты не видишь): ${names.join(', ')}.`
    : 'СВОИ САЙТЫ В МЕНЮ: пока не добавлены.';
}

export interface PromptIntegration {
  /** dpi, bschecker, regru или cloudflare. */
  provider: string;
  connected: boolean;
  /** Баланс у сервиса, если он известен: у DPI Checker в долларах, у BS Checker в кредитах. */
  balance?: string | null;
}

export interface PromptExtras {
  /** Текст «Правил парка» без шаблонных подсказок; null — владелец ничего не написал. */
  fleetRules?: string | null;
  /** Адрес этой панели: без него модель подставляла выдуманные домены вроде panel.example.com. */
  panelUrl?: string | null;
  /** Название панели из «Внешний вид» без цветовых кодов. */
  brandName?: string | null;
  /** Пояс панели (IANA, например Asia/Omsk). */
  timeZone?: string | null;
  /** Состояние интеграций; не передано — строки нет, и Ассистент спрашивает владельца. */
  integrations?: PromptIntegration[];
  /** «Свои сайты» из меню. */
  customSites?: Array<{ name: string }>;
}

/** Полная системная подсказка с учётом подробности, времени и данных панели. */
export function buildSystem(level: AssistantLevel, extras: PromptExtras = {}): string {
  const now = new Date();
  const brand = oneLine(extras.brandName ?? '', 60);
  const name = !brand || brand === 'NodeService' ? 'NodeService' : `${brand} (NodeService)`;
  return [
    `Ты — Ассистент панели ${name}. Отвечай по-русски, к владельцу обращайся на «вы».`,
    MODE,
    timeLine(now, extras.timeZone),
    extras.panelUrl
      ? `АДРЕС ЭТОЙ ПАНЕЛИ: ${extras.panelUrl}. Называй его как есть, не подставляй примеры вроде panel.example.com.`
      : '',
    TOOLS,
    DATA_RULES,
    KB_RULES,
    CHECK_RULES,
    ADVICE_RULES,
    ANSWER_STYLE,
    extras.fleetRules ? fleetRulesBlock(extras.fleetRules) : '',
    PANEL_MAP,
    integrationsLine(extras.integrations),
    customSitesLine(extras.customSites),
    levelRule(level),
  ]
    .filter(Boolean)
    .join('\n');
}
