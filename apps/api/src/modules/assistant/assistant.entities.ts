/**
 * Сущности панели для справочника Ассистента: поля берутся из тех же схем, что и у API, а подписи «откуда
 * значение, кто его меняет и где» написаны вручную. Тест требует подпись у каждого поля схемы, поэтому новое
 * поле без описания ломает сборку, а Ассистент не гадает, «откуда это значение».
 */
export interface EntityDoc {
  id: string;
  title: string;
  schema: z.ZodObject;
  /** Где владелец это видит и меняет. */
  where: string;
  fields: Record<string, string>;
  /**
   * Поля схемы, которые Ассистенту не передаются или остались от прежних версий (связь со «своими» серверами,
   * попытки починки, разборы): имя => почему не описано. Если общий контракт уберёт такое поле, справочник
   * от этого не сломается.
   */
  hidden?: Record<string, string>;
}

