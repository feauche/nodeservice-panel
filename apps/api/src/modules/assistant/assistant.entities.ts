/** Поля схемы, которые описаны для Ассистента: всё, кроме скрытых. */
export function documentedKeys(e: EntityDoc): string[] {
  return Object.keys(e.schema.shape).filter((k) => !(k in (e.hidden ?? {})));
}

/** Тип поля для человека: строка, число, да/нет, список, значения перечисления; null и необязательность отмечаются. */
export function typeLabel(t: z.ZodType): string {
  const def = (
    t as unknown as {
      def: {
        type: string;
        innerType?: z.ZodType;
        element?: z.ZodType;
        in?: z.ZodType;
        values?: unknown[];
        options?: z.ZodType[];
      };
    }
  ).def;
  if (def.type === 'nullable' && def.innerType) return `${typeLabel(def.innerType)} или null`;
  if (def.type === 'optional' && def.innerType) return typeLabel(def.innerType);
  if (def.type === 'default' && def.innerType) return typeLabel(def.innerType);
  if (def.type === 'pipe' && def.in) return typeLabel(def.in);
  if (def.type === 'array' && def.element) return `список (${typeLabel(def.element)})`;
  if (def.type === 'enum') return (t as unknown as { options: string[] }).options.join(' | ');
  if (def.type === 'literal' && def.values) return def.values.map(String).join(' | ');
  if (def.type === 'union' && def.options) return def.options.map(typeLabel).join(' или ');
  if (def.type === 'string') return 'строка';
  if (def.type === 'number') return 'число';
  if (def.type === 'boolean') return 'да/нет';
  return 'объект';
}

export function renderEntities(): string {
  const blocks = ENTITY_DOCS.map((e) => {
    const shape = e.schema.shape as Record<string, z.ZodType>;
    const lines = documentedKeys(e).map(
      (k) => `- **${k}** (${typeLabel(shape[k] as z.ZodType)}): ${e.fields[k] ?? ''}`,
    );
    return `## ${e.title} (${e.id})\nГде видно и меняется: ${e.where}.\n${lines.join('\n')}`;
  });
  return `# Сущности панели и их поля

Поля ниже соответствуют тому, что отдаёт API панели и инструменты чтения. Поле «приходит из Remnawave» в панели не меняется: на просьбу «поменяйте» объясните, где это меняется в Remnawave. Поле, которое меняет владелец в окне ноды, в «Биллинге» или в «Сценариях», он меняет сам в интерфейсе: у Ассистента инструментов записи нет, кроме базы знаний. Служебные поля прежних версий (связь со своими серверами, попытки починки, разборы) Ассистенту не передаются и здесь не описаны.

${blocks.join('\n\n')}`;
}
