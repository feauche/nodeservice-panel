/**
 * Инцидент «похоже на блокировку» заводится по падению онлайна ноды Remnawave, а в деле записан только
 * момент падения. Без текущего онлайна Джарвис при повторном разборе не видит, что всё уже вернулось, —
 * поэтому подкладываем свежий снимок ноды прямо в данные. null — нода не нашлась или Remnawave нет.
 */
export function nodeNowText(
  inc: Pick<Incident, 'serverId' | 'serverName'>,
  status: Pick<RemnawaveStatus, 'connected' | 'checkedAt' | 'nodes'> & { error?: string | null },
  serverHost: string | null,
  timeZone: string = PANEL_TIME_ZONE_DEFAULT,
): string | null {
  if (!status.connected) return null;
  const node =
    (serverHost ? status.nodes.find((n) => n.address === serverHost) : undefined) ??
    status.nodes.find((n) => n.name === inc.serverName);
  if (!node) return null;
  const at = status.checkedAt ? localClock(new Date(status.checkedAt), timeZone) : 'время снимка неизвестно';
  // Последний опрос Remnawave не удался: список нод в снимке — от прошлого удачного опроса, он не «сейчас».
  if (status.error)
    return `Нода «${node.name}»: Remnawave сейчас не отвечает панели (попытка в ${at}) — текущий онлайн неизвестен. Последнее, что панель видела: онлайн ${node.usersOnline ?? 'нет данных'}; считать это свежим нельзя.`;
  // «На связи с Remnawave» — про служебный канал ноды, а не про порт, в который стучатся пользователи.
  const state = node.isDisabled
    ? 'выключена в Remnawave вручную'
    : node.isConnected
      ? 'на связи с Remnawave (управляющая служба ноды отвечает; запущен ли сам Xray и открыт ли снаружи порт для пользователей, это не показывает)'
      : 'не на связи с Remnawave';
  return `Нода «${node.name}» сейчас (снимок Remnawave, ${at}): онлайн ${node.usersOnline ?? 'нет данных'}, ${state}. Сравните с онлайном до падения из дела: если онлайн вернулся близко к прежнему, проблема прошла сама.`;
}

/**
 * Входа в свежей проверке нет — почему: без этой строки модель не знает, молчит вход, не указан он в профиле
 * или его просто нечем было проверить. `server` — сервер дела; null — ноды нет среди серверов панели.
 */
export function entryAbsentText(server: Pick<Server, 'profile'> | null): string {
  if (!server)
    return 'Вход (мост или вход арендодателя) не проверяли: нода не привязана к серверу панели, и его профиль неизвестен.';
  const up = server.profile.upstream;
  if (!up || !isExitOnly(server.profile.roles))
    return 'Вход (мост или вход арендодателя) в профиле этого сервера не указан — отдельно вход не проверяли.';
  return up.kind === 'rent'
    ? 'Вход арендодателя указан в профиле без адреса — проверить его нечем.'
    : 'Мост указан в профиле, но проверить его нечем: сервер-мост не найден или у него нет ноды в Remnawave.';
}

/**
 * Свежая проверка порта ноды при разборе: итог и что увидел каждый проверяющий сервер. Итог назван по тому,
 * что проверено, — «порт ноды не отвечает», а не «сервер недоступен»: жив ли сервер, показывают агент и
 * порт SSH из разных стран. `serverAlive` — агент на связи: тогда молчащий порт — дело в самой ноде.
 */
export function freshCheckText(
  r: BlockCheckResult,
  opts: { timeZone?: string; now?: Date; serverAlive?: boolean } = {},
): string | null {
  const at = localClock(opts.now ?? new Date(), opts.timeZone ?? PANEL_TIME_ZONE_DEFAULT);
  const head = `Проверка порта ноды сейчас (${at}; она же проверка блокировки из России)`;
  if (r.probes.length === 0) return `${head} не удалась: ${uncheckedWhy(r)}. Опирайтесь на онлайн.`;
  const lines = [...r.probes, ...r.foreign].map((p) => `• ${p.from} — ${p.detail.trim()}`);
  const entry = r.entry;
  // Проверяли и вход — итог в первой строке относится только к выходу, о входе сказано ниже.
  const entryChecked = Boolean(entry && entry.probes.length > 0);
  const alive = Boolean(opts.serverAlive) && r.verdict === 'unreachable';
  let verdict: string;
  if (r.verdict === 'unreachable')
    verdict = `${
      r.foreign.length > 0
        ? 'порт ноды не отвечает ни из России, ни из-за рубежа'
        : 'порт ноды из России не отвечает, из-за рубежа не проверен'
    }${alive ? '; сам сервер работает (агент на связи)' : ''}`;
  else verdict = lowerFirst(BLOCK_VERDICT_LABELS[r.verdict]);
  if (entry && entryChecked) {
    lines.push(`${entry.label} (${entry.address}), из России:`);
    for (const p of entry.probes) lines.push(`• ${p.from} — ${p.detail.trim()}`);
    // Только факт: что советовать при молчащем входе (оплата аренды или письмо арендодателю), решают правила.
    const side = entrySide(r, { serverAlive: alive, bare: true });
    if (side) lines.push(side);
  } else if (entry) lines.push(entryUncheckedLine(entry));
  if (r.verdict === 'unreachable' && r.foreign.length === 0) {
    const why = foreignWhy(r);
    lines.push(`${why.charAt(0).toUpperCase()}${why.slice(1)}.`);
  }
  // Выход отвечает, а вход нет: «порт отвечает» здесь не значит «прошло» — люди идут через вход.
  const entryDown = entryChecked && entry?.verdict !== 'ok';
  const tail = entryDown
    ? 'Пока вход не отвечает, проблема не прошла, даже если порт выхода отвечает: пользователи подключаются через вход.'
    : 'Если при открытии порт не отвечал, а сейчас отвечает и онлайн вернулся — проблема прошла.';
  return `${head}${entryChecked ? ', выход' : ''}: ${verdict}.\n${lines.join('\n')}\n${tail}`;
}

/**
 * Что «Биллинг» знает об оплате сервера — для блока данных. Оплата в окне — по строке на оплату, с видом
 * и сроком словами на сейчас; в окне пусто — так и сказано (иначе модель не отличит «оплачено» от «не
 * проверяли»); оплаты самого сервера (хостинг или аренда) не заведены — панель срока не знает, и «оплата
 * в порядке» говорить нельзя, даже если к серверу привязан сертификат или домен.
 * Автопродление — отдельным блоком: это не окно оплаты. null — «Биллинг» не спрашивали или он не ответил.
 */
export function paymentText(p: PaymentWindow | null): string | null {
  if (!p) return null;
  const inWindow = [
    ...p.overdue.map((f) => `- Просрочена: ${paymentFactLine(f)}.`),
    ...p.dueSoon.map((f) => `- Срок близко: ${paymentFactLine(f)}.`),
  ];
  const auto =
    p.autoRenewed.length > 0
      ? `Автоплатёж за последние сутки (в окно оплаты не входит: панель продлила срок сама и не знает, прошло ли списание):\n${p.autoRenewed.map((f) => `- ${f}.`).join('\n')}`
      : null;
  const unknown =
    'хостинг и аренда этого сервера в «Биллинге» не заведены — срока оплаты самого сервера панель не знает';
  let main: string;
  if (inWindow.length > 0) {
    // Что с остальными оплатами: иначе не видно, заведена ли, например, аренда, когда в окне только хостинг.
    const rest =
      inWindow.length === p.total
        ? 'Других оплат у сервера в «Биллинге» нет.'
        : `Остальные оплаты сервера в окно не попали${p.next ? `; ближайшая: ${p.next}` : ''}.`;
    main = `Окно оплаты (срок оплаты этого сервера в «Биллинге» прошёл или наступит в ближайшие сутки; вид оплаты — первое слово после пометки: «Сервер» — хостинг, «Аренда» — арендодатель):\n${inWindow.join('\n')}\n${rest}${
      p.paying === 0 ? ` При этом ${unknown}.` : ''
    }`;
  } else if (p.paying === 0)
    main = `Оплата этого сервера («Биллинг»): ${unknown}.${
      p.next ? ` К серверу привязана только другая оплата: ${p.next}.` : ''
    }`;
  else
    main = `Оплата этого сервера («Биллинг»): в окне оплаты ничего нет — по записям просрочки нет, срок не близко. Это дата, записанная в панели; настоящий баланс панель не видит.${
      p.next ? ` Ближайший срок: ${p.next}.` : ''
    }`;
  return auto ? `${main}\n\n${auto}` : main;
}

/**
 * Дело и (если есть) сводка метрики одним сообщением, чтобы не тратить круги на очевидное чтение.
 * `time` — пояс панели: отметки времени панели в блоке переводятся в него, первой строкой идёт «Сейчас».
 */
export const dataBlock = (
  caseJson: unknown,
  metricText: string | null,
  nowText: string | null = null,
  payment: PaymentWindow | null = null,
  evidence: readonly string[] = [],
  time: { timeZone: string; now?: Date } | null = null,
): string => {
  const pay = paymentText(payment);
  const body = `Дело инцидента:\n${JSON.stringify(caseJson)}${
    metricText ? `\n\nИстория метрики за период:\n${metricText}` : ''
  }${nowText ? `\n\nСостояние сейчас:\n${nowText}` : ''}${pay ? `\n\n${pay}` : ''}${
    evidence.length > 0 ? `\n\nУлики, собранные панелью перед разбором:\n${evidence.join('\n\n')}` : ''
  }`;
  if (!time) return `<данные>\n${body}\n</данные>`;
  const now = time.now ?? new Date();
  // Год — всегда: иначе модели неоткуда узнать, какой сейчас год (давность статей, прошлых дел).
  const head = `Сейчас: ${localDateTime(now, time.timeZone, now, { year: true })} (${zoneLabel(now, time.timeZone)}). Время в деле, уликах и ответах панели — в этом часовом поясе; отметки словами («30 сентября, 15:56:03») переведены в него и в начале строк журнала службы. Остальное время внутри строк журналов и вывода команд — по часам самого сервера.`;
  return `<данные>\n${head}\n${localizeIsoTimes(body, time.timeZone, now)}\n</данные>`;
};

