/** Сколько знаков правил уходит в инструкцию Ассистенту; остальное читается поиском по базе знаний. */
export const FLEET_RULES_MAX = 3500;

/**
 * Текст правил для Ассистента без шаблонных подсказок и вступления. Пусто (null), если владелец ещё ничего не
 * написал: тогда в инструкцию ничего не добавляется. Заголовки разделов без записей тоже отбрасываются.
 */
export function fleetRulesText(content: string): string | null {
  const lines = content.replace(/\r/g, '').split('\n');
  const out: string[] = [];
  let heading: string | null = null;
  for (const raw of lines) {
    const line = raw.trimEnd();
    const t = line.trim();
    if (!t) continue;
    if (t.startsWith('# ')) continue;
    if (t.startsWith('>')) continue;
    if (/^_.+_$/.test(t)) continue;
    if (t.startsWith('## ')) {
      heading = t;
      continue;
    }
    if (heading) {
      out.push(heading);
      heading = null;
    }
    out.push(line);
  }
  if (out.length === 0) return null;
  const text = out.join('\n');
  return text.length > FLEET_RULES_MAX
    ? `${text.slice(0, FLEET_RULES_MAX)}\n… (текст обрезан; полный текст в базе знаний: статья «${FLEET_RULES_TITLE}», search_kb)`
    : text;
}

