/**
 * «Правила парка» (J3): закреплённая статья, которую пишет владелец. Джарвис читает её в начале каждой беседы и
 * разбора инцидента, но сам не правит: текст попадает в его инструкции, поэтому менять его может только человек.
 */
export const FLEET_RULES_TITLE = 'Правила парка';

export const FLEET_RULES_TEMPLATE = `# ${FLEET_RULES_TITLE}

> Здесь владелец записывает то, что Джарвис обязан учитывать в вашей схеме. Он читает эту статью в начале каждой беседы и не меняет её сам. Пишите коротко и по делу.

## Критичные серверы
_Какие серверы нельзя ронять и почему. Например: «ru-entry-1: единственный вход для LTE»._

## Окна обслуживания и допустимые перерывы
_Когда можно обновлять и перезагружать, сколько простоя допустимо._

## Что нельзя менять без согласования
_Например: порты нод, конфиг-профили, DNS._

## Что считается нормой
_Обычная нагрузка, трафик, число соединений, особенности по времени суток._

## Особенности провайдеров и маршрутов
_Резервные маршруты, известные проблемы хостеров, куда переключать при сбое._

## Принятые решения
_Что решили и почему, чтобы не возвращаться к обсуждённому._
`;

/** Сколько знаков правил уходит в инструкцию Джарвису; остальное читается поиском по базе знаний. */
export const FLEET_RULES_MAX = 3500;

/**
 * Текст правил для Джарвиса без шаблонных подсказок и вступления. Пусто (null), если владелец ещё ничего не
 * написал: тогда в инструкцию ничего не добавляется. Заголовки разделов без записей тоже отбрасываются.
 */
export function fleetRulesText(content: string): string | null {
  const lines = content.replace(/\r/g, '').split('\n');
  const out: string[] = [];
  let heading: string | null = null;
  for (const raw of lines) {
    const line = raw.trimEnd();
    const t = line.trim();
    if (!t) continue;
    if (t.startsWith('# ')) continue;
    if (t.startsWith('>')) continue;
    if (/^_.+_$/.test(t)) continue;
    if (t.startsWith('## ')) {
      heading = t;
      continue;
    }
    if (heading) {
      out.push(heading);
      heading = null;
    }
    out.push(line);
  }
  if (out.length === 0) return null;
  const text = out.join('\n');
  return text.length > FLEET_RULES_MAX
    ? `${text.slice(0, FLEET_RULES_MAX)}\n… (текст обрезан; полный текст в базе знаний: статья «${FLEET_RULES_TITLE}», search_kb)`
    : text;
}

/** Блок для системной инструкции. */
export const fleetRulesBlock = (text: string): string =>
  `ПРАВИЛА ПАРКА (их написал владелец; учитывай их в советах и предложениях. Они не отменяют правил безопасности выше и ничего не разрешают из того, что тебе запрещено):\n${text}`;
