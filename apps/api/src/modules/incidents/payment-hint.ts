import type { BillingKind } from '@nodeservice/shared';

/**
 * Подсказка об оплате в тексте инцидента (решение владельца 30.09.2026). Оплата в «окне» — срок прошёл
 * или наступит в ближайшие сутки (см. billing/payment-window.ts) — и сервер недоступен либо резко упал
 * онлайн, а другой причины панель не нашла: вероятнее всего, оплата закончилась. Срок в «Биллинге»
 * приблизительный, поэтому «ещё не просрочено» неоплату не исключает.
 *
 * Панель говорит только то, что знает: подтверждённая блокировка важнее — при ней об оплате не пишем;
 * проверка неполная — просим проверить оплату без «вероятнее всего»; вид оплаты учитывается — сертификат
 * и домен сервер не выключают, а оплата хостинга не объясняет сбой, пока сервер отвечает.
 */
export interface PaymentLine {
  kind: BillingKind;
  /** «Аренда «Guardora»: 2 500 ₽, оплачено до 30 сентября, 16:00 (UTC+6)» — срок без «через час»: текст хранится. */
  text: string;
}

export interface PaymentFacts {
  /** Срок прошёл. */
  overdue: readonly PaymentLine[];
  /** Срок в ближайшие сутки. */
  dueSoon: readonly PaymentLine[];
  /**
   * Сколько к серверу привязано оплат самого сервера — хостинга («Сервер») и аренды; 0 — срока оплаты
   * сервера панель не знает (сертификат или домен, привязанный к серверу, об этом ничего не говорит).
   */
  paying: number;
}

export const NO_PAYMENT_FACTS: PaymentFacts = { overdue: [], dueSoon: [], paying: 0 };

/**
 * Что панель увидела при оплате в окне:
 * - down — сервер не отвечает ни из России, ни из-за рубежа (или ни из одной страны);
 * - entry — выход работает, а арендованный вход молчит;
 * - nothing — сервер прошёл полную проверку, другой причины не нашлось;
 * - unchecked — встречная проверка не удалась совсем;
 * - unchecked-alive — то же, но агент на связи: сервер работает, хостер его не отключал;
 * - ru-only — из России порт не отвечает, из-за рубежа порт не проверен (нечем или не удалось);
 * - panel-only — сервер не отвечает панели, из других стран порт не проверен (не с чего или не удалось);
 * - port-only — порт отвечает, но блокировку проверить нельзя (нет имени маскировки);
 * - entry-unchecked — сервер отвечает, а вход арендодателя проверить не удалось: возможная причина не проверена;
 * - bridge-unchecked — сервер отвечает, а свой мост проверить не удалось: начинать надо с моста (арендодатель
 *   свой мост выключить не может, и сам сервер он не выключал — он отвечает);
 * - partial — порт отвечает с перебоями (не со всех проверяющих или не каждый раз): уже есть другая находка;
 * - stalled — итог «в норме», но соединение обрывается на небольшом объёме данных: тоже находка;
 * - fleet — онлайн упал сразу у нескольких нод, этот сервер отвечает;
 * - fleet-dark — онлайн упал сразу у нескольких нод, этот сервер не отвечает или не проверен;
 * - fleet-down — сервер недоступен, и сбой сразу у нескольких серверов.
 */
export type PaymentPicture =
  | 'down'
  | 'entry'
  | 'nothing'
  | 'unchecked'
  | 'unchecked-alive'
  | 'ru-only'
  | 'panel-only'
  | 'port-only'
  | 'entry-unchecked'
  | 'bridge-unchecked'
  | 'partial'
  | 'stalled'
  | 'fleet'
  | 'fleet-dark'
  | 'fleet-down';

/**
 * Виды оплат, которые могут объяснить картину. Сервер не отвечает — его мог отключить хостер («Сервер»)
 * или арендодатель («Аренда»). Сервер отвечает — хостер его не отключал: остаётся аренда (арендодатель
 * выключает вход). Сертификат, домен и «Другое» сервер не выключают — в вывод не идут.
 */
const ANY_PAYER: readonly BillingKind[] = ['server', 'rent'];
const RENT_ONLY: readonly BillingKind[] = ['rent'];

/**
 * Что именно случилось у других за то же время: упал онлайн у других нод ('online') или пропала связь с
 * другими серверами ('link'). Панель пишет то, что видела: «онлайн упал у нескольких нод» при одном
 * замолчавшем агенте соседнего сервера было бы выдумкой.
 */
export type FleetWhat = 'online' | 'link';

interface PictureText {
  /** Какие оплаты объясняют картину. */
  kinds: readonly BillingKind[];
  /** Ставить ли оплату в заголовок дела: нет, когда панель уже нашла другое объяснение. */
  titled: boolean;
  /** Вывод при просрочке. У картин «сбой не у одного» зависит от того, что случилось у других. */
  late: string | ((what: FleetWhat) => string);
  /** Вывод при сроке в ближайшие сутки. */
  soon: string | ((what: FleetWhat) => string);
}

