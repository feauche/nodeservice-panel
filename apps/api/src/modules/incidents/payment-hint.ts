/**
 * Догадка по названию для арендованного сервера, недоступного целиком, когда оплаты в окне нет.
 * `payment: null` — «Биллинг» не спрашивали (ноды нет среди серверов панели) или он не ответил.
 * Оплата заведена и срок не близко — догадку не пишем: панели нечем её подкрепить.
 */
export function rentalGuess(payment: PaymentFacts | null): string | null {
  const head = 'Сервер арендован: если он недоступен целиком, возможно, не оплачена аренда';
  if (payment === null) return `${head} (оплату в «Биллинге» панель проверить не смогла).`;
  if (payment.paying === 0)
    return `${head} (оплата этого сервера в «Биллинге» не заведена — срока панель не знает).`;
  return null;
}
