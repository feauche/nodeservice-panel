function relevant(
  p: PaymentFacts,
  picture: PaymentPicture,
): { overdue: PaymentLine[]; dueSoon: PaymentLine[] } {
  const kinds = PICTURES[picture].kinds;
  return {
    overdue: p.overdue.filter((f) => kinds.includes(f.kind)),
    dueSoon: p.dueSoon.filter((f) => kinds.includes(f.kind)),
  };
}

/** Факты для дела: каждая подходящая оплата отдельной строкой с подписью. */
export function paymentLines(p: PaymentFacts, picture: PaymentPicture): string[] {
  const r = relevant(p, picture);
  return [
    ...r.overdue.map((f) => `💳 Просрочена оплата: ${f.text}.`),
    ...r.dueSoon.map((f) => `💳 Срок оплаты близко: ${f.text}.`),
  ];
}

/**
 * Вывод об оплате одной строкой; null — подходящей оплаты в окне нет. Просрочка важнее близкого срока.
 * `fleet` — что случилось у других (нужно только картинам «сбой не у одного»): по умолчанию то, о чём сама
 * картина, — упавший онлайн для падения онлайна, пропавшая связь для недоступного сервера.
 */
export function paymentConclusion(
  p: PaymentFacts,
  picture: PaymentPicture,
  fleet?: FleetWhat,
): string | null {
  const r = relevant(p, picture);
  if (r.overdue.length === 0 && r.dueSoon.length === 0) return null;
  const text = r.overdue.length > 0 ? PICTURES[picture].late : PICTURES[picture].soon;
  return typeof text === 'string' ? text : text(fleet ?? (picture === 'fleet-down' ? 'link' : 'online'));
}

/** Ставить ли оплату в заголовок дела: да, если есть вывод и панель не нашла другого объяснения. */
export function paymentTitled(p: PaymentFacts, picture: PaymentPicture): boolean {
  return PICTURES[picture].titled && paymentConclusion(p, picture) !== null;
}

/**
 * Подпись дела «Сервер недоступен» с учётом оплаты; undefined — обычная подпись вида: подходящей оплаты в
 * окне нет или картина оплату в заголовок не ставит (сбой сразу у нескольких серверов).
 */
export function serverDownLabel(p: PaymentFacts, picture: PaymentPicture = 'down'): string | undefined {
  if (!paymentTitled(p, picture)) return undefined;
  return relevant(p, picture).overdue.length > 0
    ? 'Сервер недоступен — просрочена оплата'
    : 'Сервер недоступен — проверьте оплату';
}

