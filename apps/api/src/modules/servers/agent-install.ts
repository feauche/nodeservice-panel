import { stripAnsi } from './servers.problems.js';
import { shellQuote } from './ssh.service.js';

/** Привязка агента к панели (ключ и адрес). Пока файл на месте, агент новый токен не берёт. */
export const AGENT_STATE_PATH = '/var/lib/nodeservice-agent/state.json';
/** Как установка называется в текстах ошибок — вместо самой команды, в которой лежит токен. */
export const AGENT_INSTALL_LABEL = 'установка агента';
/**
 * Сколько панель ждёт установку: скрипт, бинарь около 8 МБ и суммы с GitHub, пользователь, systemd. Общих
 * 20 секунд на команду не хватало серверам с медленным доступом к GitHub (обновлению агента на то же
 * скачивание отведено три минуты; здесь шагов больше).
 */
export const AGENT_INSTALL_TIMEOUT_MS = 5 * 60_000;

export interface AgentInstallParams {
  /** GitHub-репозиторий агента: «владелец/имя». */
  repo: string;
  token: string;
  /** Публичный адрес панели. */
  panel: string;
}

const scriptUrl = (repo: string) => `https://github.com/${repo}/releases/latest/download/install.sh`;

/**
 * Команда для ручной установки — её видит и копирует владелец (запасной путь, когда панель не заходит по
 * SSH). Скрипт сначала скачивается в файл: по конвейеру «curl | sh» сбой скачивания выглядел успехом (код
 * выхода — от sh с пустым вводом), а привязка работающего агента к тому моменту уже была удалена. Теперь
 * привязка откладывается только после успешного скачивания и возвращается на место, если скрипт упал (а
 * новый агент не успел привязаться сам); любой сбой даёт ненулевой код. Обёртка `sh -c` — чтобы команда
 * одинаково работала в любой оболочке, куда её вставят.
 */
export function agentInstallCommand({ repo, token, panel }: AgentInstallParams): string {
  const inner = [
    `S=${AGENT_STATE_PATH}`,
    `f=$(mktemp) && curl -fsSL -o "$f" ${scriptUrl(repo)} && { mv -f "$S" "$S.prev" 2>/dev/null; sh "$f" --token ${token} --panel ${panel}; }`,
    'c=$?',
    '[ $c = 0 ] || [ -e "$S" ] || mv -f "$S.prev" "$S" 2>/dev/null',
    'rm -f "$f" "$S.prev"',
    'exit $c',
  ].join('; ');
  return `sh -c ${shellQuote(inner)}`;
}

/**
 * Установка самой панелью по SSH. С привязкой поступает так же, как ручная команда: откладывает её после
 * скачивания и возвращает на место, если установка не удалась, — работающий агент не пропадёт после
 * перезагрузки сервера. Отличие — причина неудачи печатается словами (её покажут в панели и в Журнале),
 * владелец у терминала видит вывод сам. Маркер в первой строке — для логов и тестового sshd; NS_AGENT_STATE
 * переопределяется только в тестах (настоящий шелл, временная папка).
 */
export function agentInstallScript({ repo, token, panel }: AgentInstallParams): string {
  return [
    '# ns-agent:install',
    `S="\${NS_AGENT_STATE:-${AGENT_STATE_PATH}}"`,
    'command -v curl >/dev/null 2>&1 || { echo "На сервере нет curl — без него установочный скрипт не скачать. Установите curl и повторите."; exit 1; }',
    'F="$(mktemp)" || { echo "Не удалось создать временный файл на сервере."; exit 1; }',
    `trap 'rm -f "$F"' EXIT`,
    // Сырой текст ошибки curl (английский) владельцу не показываем — причину называем сами: по коду ответа
    // GitHub и коду выхода curl. Ключ -f не ставим: с ним код выхода при отказе сервера зависит от версии
    // curl (22 или 56), а страница ошибки всё равно не выполняется — смотрим на код ответа.
    `code="$(curl -sSL --max-time 60 -o "$F" -w '%{http_code}' ${shellQuote(scriptUrl(repo))} 2>/dev/null)"`,
    'rc=$?',
    'if [ "$rc" -ne 0 ] || [ "$code" != 200 ] || [ ! -s "$F" ]; then',
    '  case "$rc" in',
    '    0) if [ "$code" = 200 ]; then why="GitHub отдал пустой файл"; else why="GitHub ответил ошибкой $code"; fi ;;',
    '    6) why="сервер не находит адрес GitHub" ;;',
    '    7) why="сервер не может соединиться с GitHub" ;;',
    '    28) why="скачивание с GitHub не уложилось в минуту" ;;',
    '    35|60) why="защищённое соединение с GitHub не устанавливается" ;;',
    '    *) why="скачивание завершилось с ошибкой $rc" ;;',
    '  esac',
    '  echo "Установочный скрипт агента не скачался: $why. На сервере ничего не изменено."',
    '  exit 1',
    'fi',
    // Старая привязка иначе переживает установку: агент пишет «токен игнорирую», и новый токен пропадает
    // зря — повторная установка ничего не меняла (случай «Казахстан-1»). Поэтому на время установки убираем.
    '[ -e "$S" ] && mv -f "$S" "$S.prev"',
    `if sh "$F" --token ${shellQuote(token)} --panel ${shellQuote(panel)}; then`,
    '  rm -f "$S.prev"',
    'else',
    '  rc=$?',
    // Новый агент успел привязаться — его привязку не трогаем; иначе возвращаем прежнюю.
    '  if [ -e "$S" ]; then rm -f "$S.prev"',
    '  elif [ -e "$S.prev" ]; then mv -f "$S.prev" "$S" && echo "Прежняя привязка агента возвращена на место."',
    '  fi',
    '  exit "$rc"',
    'fi',
  ].join('\n');
}

/**
 * Хвост вывода установки — причина неудачи для текста ошибки. Коды цвета убираем до обрезки: иначе
 * обрезанный посередине код остался бы в тексте мусором.
 */
export const installFailure = (output: string, code: number): string =>
  stripAnsi(output).trim().slice(-300) || `код ${code}`;
